    note_too_long: [`Описание длиннее ${NOTE_MAX} символов. Сократите его.`, `Сипаттама ${NOTE_MAX} таңбадан ұзын. Қысқартыңыз.`],
    due_past: ['Срок не может быть в прошлом.', 'Мерзім өткен күн бола алмайды.'],
    no_depts: ['В шаблоне должен остаться хотя бы один отдел.', 'Үлгіде кемінде бір бөлім қалуы керек.'],
    login_taken: ['Такой логин уже занят. Придумайте другой.', 'Бұл логин бос емес. Басқасын ойлап табыңыз.'],
    weak_password: [`Пароль должен быть не короче ${PASSWORD_MIN} символов.`, `Құпиясөз кемінде ${PASSWORD_MIN} таңба болуы керек.`],
